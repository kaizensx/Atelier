import Testing
@testable import DockCore

@Test func clipboardSkipsPrivateCopies() {
    for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
        #expect(ClipboardPrivacy.keptText(types: ["public.utf8-plain-text", type], text: "secret") == nil)
    }
    #expect(ClipboardPrivacy.keptText(types: nil, text: "x") == nil)
    #expect(ClipboardPrivacy.keptText(types: ["public.utf8-plain-text"], text: "  \n") == nil)
    #expect(ClipboardPrivacy.keptText(types: ["public.utf8-plain-text"], text: " hi \n") == "hi")
    #expect(ClipboardPrivacy.keptText(types: ["public.utf8-plain-text"], text: "abcdef", limit: 3) == "abc")
}

@Test func changingACornerKeepsItsModifier() {
    var plist: [String: Any] = ["wvous-tl-corner": 2, "wvous-tl-modifier": 1_048_576]
    AppleHotCorner.set("tl", to: 4, in: &plist)
    #expect(plist["wvous-tl-corner"] as? Int == 4)
    #expect(plist["wvous-tl-modifier"] as? Int == 1_048_576)
    AppleHotCorner.set("br", to: 13, in: &plist)
    #expect(plist["wvous-br-modifier"] as? Int == 0)
}

@Test func everyAppleCornerValueHasALabel() {
    for value in [0, 1, 2, 3, 4, 5, 6, 10, 11, 12, 13, 14] {
        let options = AppleHotCorner.options(current: value)
        #expect(options.contains { $0.0 == AppleHotCorner.normalized(value) }, "\(value)")
        #expect(options.count == AppleHotCorner.actions.count)
    }
    #expect(AppleHotCorner.options(current: 7).last?.1 == "Other (7)")
}
